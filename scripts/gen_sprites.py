# ---------------------------------------------------------------------------
# Sprite silhouettes — 16x16 pixel patterns per class, per clip row, per frame
#
# Each pattern is a list of strings (top-to-bottom rows of pixels).
# '#' = foreground (body), 'o' = outline, 'a' = accent, 's' = shadow,
# 'h' = highlight, 'k' = skin, 'w' = weapon, '.' = transparent
# ---------------------------------------------------------------------------

# Helper: resolve pattern char → palette color
def resolve(ch: str, pal: dict) -> tuple:
    return {
        '#': pal["body"],
        'o': pal["outline"],
        'a': pal["accent"],
        's': pal["shadow"],
        'h': pal["highlight"],
        'k': pal["skin"],
        'w': pal["weapon"],
        '.': TRANSPARENT,
    }.get(ch, TRANSPARENT)

def draw_pattern(canvas, ox: int, oy: int, pattern: list[str], pal: dict) -> None:
    for y, row in enumerate(pattern):
        for x, ch in enumerate(row):
            put(canvas, ox + x, oy + y, resolve(ch, pal))

