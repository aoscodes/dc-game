# ---------------------------------------------------------------------------
# Minimal pure-stdlib PNG writer
# ---------------------------------------------------------------------------

def _png_chunk(chunk_type: bytes, data: bytes) -> bytes:
    c = chunk_type + data
    return struct.pack(">I", len(data)) + c + struct.pack(">I", zlib.crc32(c) & 0xFFFFFFFF)

def write_png(path: str, width: int, height: int, pixels: list[list[tuple]]) -> None:
    """Write an RGBA PNG from a 2-D list of (r,g,b,a) tuples."""
    raw = b""
    for row in pixels:
        raw += b"\x00"  # filter type: None
        for r, g, b, a in row:
            raw += bytes([r, g, b, a])
    compressed = zlib.compress(raw, 9)

    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(_png_chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)))
        f.write(_png_chunk(b"IDAT", compressed))
        f.write(_png_chunk(b"IEND", b""))

# ---------------------------------------------------------------------------
# Pixel drawing helpers
# ---------------------------------------------------------------------------

TRANSPARENT = (0, 0, 0, 0)

def new_canvas(w: int, h: int) -> list[list[tuple]]:
    return [[TRANSPARENT] * w for _ in range(h)]

def put(canvas, x: int, y: int, color: tuple) -> None:
    if 0 <= y < len(canvas) and 0 <= x < len(canvas[0]):
        canvas[y][x] = color

def fill_rect(canvas, x: int, y: int, w: int, h: int, color: tuple) -> None:
    for dy in range(h):
        for dx in range(w):
            put(canvas, x + dx, y + dy, color)

def draw_pixels(canvas, ox: int, oy: int, pattern: list[str], fg: tuple, bg: tuple = TRANSPARENT) -> None:
    """Draw a pattern string grid. '#' = fg, '.' = bg (default transparent), ' ' = skip."""
    for y, row in enumerate(pattern):
        for x, ch in enumerate(row):
            if ch == '#':
                put(canvas, ox + x, oy + y, fg)
            elif ch == '.':
                put(canvas, ox + x, oy + y, bg)

def lerp_color(a: tuple, b: tuple, t: float) -> tuple:
    return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(4))

def flash_color(base: tuple, flash: tuple, t: float) -> tuple:
    """Blend base toward flash color by t (0=base, 1=flash)."""
    return lerp_color(base, flash, t)

