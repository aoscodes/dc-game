CLIP_ORDER = ["idle", "attack", "hurt", "die"]
CLIP_FRAMES = {"idle": 4, "attack": 4, "hurt": 3, "die": 6}

def build_sheet(class_name: str, clips: dict, pal: dict, frame_w: int, frame_h: int) -> list[list[tuple]]:
    max_frames = max(CLIP_FRAMES.values())  # 6
    sheet_w = max_frames * frame_w
    sheet_h = len(CLIP_ORDER) * frame_h
    canvas = new_canvas(sheet_w, sheet_h)

    for row_idx, clip_name in enumerate(CLIP_ORDER):
        frames = clips[clip_name]
        for col_idx, frame_pattern in enumerate(frames):
            ox = col_idx * frame_w
            oy = row_idx * frame_h
            draw_pattern(canvas, ox, oy, frame_pattern, pal)

    return canvas

def make_atlas(class_name: str, frame_w: int, frame_h: int) -> dict:
    return {
        "frame_w": frame_w,
        "frame_h": frame_h,
        "clips": {
            "idle":   {"row": 0, "frames": CLIP_FRAMES["idle"],   "fps": 6,  "loop": True},
            "attack": {"row": 1, "frames": CLIP_FRAMES["attack"], "fps": 12, "loop": False},
            "hurt":   {"row": 2, "frames": CLIP_FRAMES["hurt"],   "fps": 10, "loop": False},
            "die":    {"row": 3, "frames": CLIP_FRAMES["die"],    "fps": 8,  "loop": False},
        },
    }

