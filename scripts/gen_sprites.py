    horn0=_HORN_ROW, horn1=_HORN_ROW2, horn2=_HORN_ROW3,
    head0=_HEAD_R0, head1=_HEAD_R1, head2=_HEAD_R2,
    head3=_HEAD_R3, head4=_HEAD_R4, head5=_HEAD_R5,
    torso0=_TORSO_R0, torso1=_TORSO_R1, torso2=_TORSO_R2,
    torso3=_TORSO_R3, torso4=_TORSO_R4,
