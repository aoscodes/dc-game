def _boss_dissolve(t: float) -> list[str]:
    """t=0 fully visible shadow, t=1 almost gone. Uses 's' (shadow) pixels."""
    rows = [_BLANK] * 12
    # shrinking silhouette — get narrower each step
    w = max(2, int(20 * (1 - t)))
    pad = (20 - w) // 2 + 6
    for _ in range(8):
        rows.append(_row32("." * pad + "o" + "s" * w + "o" + "." * (32 - pad - w - 2)))
    rows += [_BLANK] * (32 - len(rows))
    return [_row32(r) for r in rows[:32]]

